"""Self-contained HTML/CSS/JS를 bounded C++ header로 생성한다."""

from __future__ import annotations

import argparse
import hashlib
import json
import re
from dataclasses import dataclass
from pathlib import Path


class BundleError(ValueError):
    pass


@dataclass(frozen=True)
class BundleConfig:
    owner_root: Path
    html: Path
    style: Path
    script: Path
    generated_header: Path
    cpp_namespace: str
    max_source_bytes: int
    max_bundle_bytes: int


_ALLOWED_KEYS = {
    "schema_version", "owner_root", "html", "style", "script",
    "generated_header", "cpp_namespace", "max_source_bytes", "max_bundle_bytes",
}
_EXTERNAL_PATTERN = re.compile(
    r"(?:https?:)?//|<\s*(?:script|link)\b[^>]+(?:src|href)\s*=",
    re.IGNORECASE,
)


def _resolve_under(root: Path, relative: object, label: str) -> Path:
    if not isinstance(relative, str) or not relative or "\\" in relative:
        raise BundleError(f"{label} must be a non-empty POSIX relative path")
    candidate_path = Path(relative)
    if candidate_path.is_absolute() or ".." in candidate_path.parts:
        raise BundleError(f"{label} escapes its owner root")
    candidate = (root / candidate_path).resolve()
    try:
        candidate.relative_to(root)
    except ValueError as error:
        raise BundleError(f"{label} escapes its owner root") from error
    return candidate


def load_config(config_path: Path) -> BundleConfig:
    path = config_path.resolve()
    raw = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(raw, dict) or set(raw) != _ALLOWED_KEYS:
        raise BundleError("web bundle config fields do not match the schema")
    if raw["schema_version"] != 1:
        raise BundleError("unsupported web bundle schema version")
    owner_relative = raw["owner_root"]
    if not isinstance(owner_relative, str):
        raise BundleError("owner_root must be a relative path")
    owner_root = _resolve_under(path.parent, owner_relative, "owner_root")
    namespace = raw["cpp_namespace"]
    if not isinstance(namespace, str) or not re.fullmatch(
        r"[A-Za-z_]\w*(?:::[A-Za-z_]\w*)*", namespace
    ):
        raise BundleError("cpp_namespace is invalid")
    limits = (raw["max_source_bytes"], raw["max_bundle_bytes"])
    if any(not isinstance(value, int) or value <= 0 for value in limits):
        raise BundleError("bundle limits must be positive integers")
    sources = [
        _resolve_under(owner_root, raw[name], name)
        for name in ("html", "style", "script")
    ]
    output = _resolve_under(owner_root, raw["generated_header"], "generated_header")
    if len(set(sources)) != len(sources) or output in sources:
        raise BundleError("web bundle paths must be unique")
    return BundleConfig(
        owner_root, sources[0], sources[1], sources[2], output, namespace,
        limits[0], limits[1],
    )


def _read_source(path: Path, limit: int) -> str:
    data = path.read_bytes()
    if len(data) > limit:
        raise BundleError(f"source exceeds limit: {path.name}")
    try:
        text = data.decode("utf-8")
    except UnicodeDecodeError as error:
        raise BundleError(f"source is not UTF-8: {path.name}") from error
    if _EXTERNAL_PATTERN.search(text):
        raise BundleError(f"external resource is forbidden: {path.name}")
    return text.strip()


def render_bundle(config: BundleConfig) -> tuple[str, str]:
    html = _read_source(config.html, config.max_source_bytes)
    style = _read_source(config.style, config.max_source_bytes)
    script = _read_source(config.script, config.max_source_bytes)
    if html.count("{{STYLE}}") != 1 or html.count("{{SCRIPT}}") != 1:
        raise BundleError("HTML must contain one STYLE and one SCRIPT placeholder")
    bundle = html.replace("{{STYLE}}", style).replace("{{SCRIPT}}", script) + "\n"
    encoded = bundle.encode("utf-8")
    if len(encoded) > config.max_bundle_bytes:
        raise BundleError("embedded web bundle exceeds its total limit")
    if ')HMI_WEB"' in bundle:
        raise BundleError("bundle collides with the C++ raw string delimiter")
    digest = hashlib.sha256(encoded).hexdigest()
    header = "\n".join([
        "// Generated by tools/assets/web/embed_web_bundle.py. Do not edit.",
        "#pragma once", "", "#include <cstddef>", "",
        f"namespace {config.cpp_namespace} {{", "",
        f'inline constexpr char kBundleSha256[] = "{digest}";',
        'inline constexpr char kBundle[] = R"HMI_WEB(' + bundle + ')HMI_WEB";',
        "inline constexpr std::size_t kBundleSize = sizeof(kBundle) - 1U;",
        f"static_assert(kBundleSize <= {config.max_bundle_bytes}U,",
        '              "embedded web bundle exceeds firmware budget");',
        "", f"}}  // namespace {config.cpp_namespace}", "",
    ])
    return header, digest


def run(config_path: Path, check: bool) -> tuple[Path, str]:
    config = load_config(config_path)
    header, digest = render_bundle(config)
    if check:
        try:
            current = config.generated_header.read_text(encoding="utf-8")
        except FileNotFoundError as error:
            raise BundleError("generated web bundle is missing") from error
        if current != header:
            raise BundleError("generated web bundle is stale")
    else:
        config.generated_header.parent.mkdir(parents=True, exist_ok=True)
        config.generated_header.write_text(header, encoding="utf-8", newline="\n")
    return config.generated_header, digest


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", type=Path, required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        output, digest = run(args.config, args.check)
    except (BundleError, OSError, json.JSONDecodeError) as error:
        parser.error(str(error))
    action = "checked" if args.check else "generated"
    print(f"{action} web bundle: {output} sha256={digest}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
